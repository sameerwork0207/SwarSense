"""
SwarSense — MusicBrainz Enricher (Phase 2)
============================================
Enriches an identified recording with metadata from the MusicBrainz database.

MusicBrainz is NOT an audio identification service.
It is used ONLY AFTER a recording has been identified (status=IDENTIFIED)
and a usable MusicBrainz Recording ID (MBID) is available.

Privacy:
  MusicBrainz is a public, open database. No audio is transmitted.
  Requests are identified by User-Agent per their guidelines.

Rate limiting:
  MusicBrainz requires ≤1 request/second from any IP.
  A 1-second sleep is inserted before each API call.

CRITICAL RAGA RULE:
  If MusicBrainz returns tags or work relationships mentioning a raga,
  these are labeled as EXTERNAL REFERENCE information.
  They must NEVER be presented as:
    "SwarSense detected raga X."
  The UI must clearly show:
    "External reference: this recording is associated with [raga X] according to MusicBrainz."

Source attribution:
  Every fact returned by this enricher includes:
    source_name = "MusicBrainz"
    url = "https://musicbrainz.org/recording/{mbid}"
    disclaimer = "External reference — retrieved from MusicBrainz. Not generated by SwarSense."

API documentation: https://musicbrainz.org/doc/MusicBrainz_API
"""

from __future__ import annotations

import time
from typing import Optional

from app.intelligence.base import (
    EnrichmentFact,
    EnrichmentResult,
    EnrichmentSource,
    ResolvedIdentification,
)
from app.utils.logger import get_logger

logger = get_logger(__name__)

_MB_API_BASE = "https://musicbrainz.org/ws/2"
_MB_USER_AGENT = "SwarSense/2.0 (academic-project; https://github.com/swarsense)"
_MB_INCLUDES = "artists+releases+tags+isrcs+url-rels+work-rels"
_HTTP_TIMEOUT = 10
_RATE_LIMIT_SLEEP = 1.1  # slightly > 1s to be safe


class MusicBrainzEnricher:
    """
    Enriches identified recordings with MusicBrainz metadata.

    Retrieves: composer, lyricist, language, genre tags, ISRC, release info,
    instrumentation tags, and external URLs (Discogs, Spotify, YouTube, etc.).

    All facts are labeled as external reference with full disclaimer.
    """

    def __init__(self, http_timeout: int = _HTTP_TIMEOUT) -> None:
        self._http_timeout = http_timeout

    def enrich(self, identification: ResolvedIdentification) -> EnrichmentResult:
        """
        Retrieve MusicBrainz metadata for an identified recording.

        Args:
            identification: A ResolvedIdentification with status=IDENTIFIED and
                            a valid mbid field.

        Returns:
            EnrichmentResult with zero or more EnrichmentSource objects.
            Never raises — errors are returned as error field in EnrichmentResult.
        """
        try:
            return self._enrich_internal(identification)
        except Exception as exc:
            logger.error(f"[MusicBrainz] Enrichment failed: {exc}", exc_info=True)
            return EnrichmentResult(
                sources=[],
                error=f"MusicBrainz enrichment failed: {exc}",
            )

    def _enrich_internal(self, identification: ResolvedIdentification) -> EnrichmentResult:
        mbid = identification.mbid
        if not mbid:
            logger.info("[MusicBrainz] No MBID available — skipping enrichment.")
            return EnrichmentResult(sources=[], error="No MusicBrainz Recording ID available.")

        try:
            import httpx
        except ImportError:
            return EnrichmentResult(sources=[], error="httpx not installed.")

        # Respect MusicBrainz rate limit
        logger.debug(f"[MusicBrainz] Rate-limit sleep {_RATE_LIMIT_SLEEP}s")
        time.sleep(_RATE_LIMIT_SLEEP)

        url = f"{_MB_API_BASE}/recording/{mbid}"
        params = {"inc": _MB_INCLUDES, "fmt": "json"}
        headers = {"User-Agent": _MB_USER_AGENT}

        logger.info(f"[MusicBrainz] Fetching recording/{mbid}")
        try:
            resp = httpx.get(url, params=params, headers=headers, timeout=self._http_timeout)
            if resp.status_code == 404:
                logger.info(f"[MusicBrainz] Recording {mbid} not found.")
                return EnrichmentResult(sources=[], error=f"Recording {mbid} not found in MusicBrainz.")
            resp.raise_for_status()
            data = resp.json()
        except httpx.TimeoutException:
            return EnrichmentResult(sources=[], error=f"MusicBrainz request timed out after {self._http_timeout}s.")
        except httpx.HTTPStatusError as exc:
            return EnrichmentResult(sources=[], error=f"MusicBrainz HTTP error {exc.response.status_code}.")
        except Exception as exc:
            return EnrichmentResult(sources=[], error=f"MusicBrainz network error: {exc}")

        return self._parse_recording(data, mbid)

    def _parse_recording(self, data: dict, mbid: str) -> EnrichmentResult:
        """Parse MusicBrainz recording JSON into EnrichmentResult."""
        facts: list[EnrichmentFact] = []
        mb_url = f"https://musicbrainz.org/recording/{mbid}"

        # ── Basic recording info ──────────────────────────────────────────────
        title = data.get("title")
        if title:
            facts.append(EnrichmentFact(field="Title", value=title))

        length_ms = data.get("length")
        if length_ms:
            facts.append(EnrichmentFact(
                field="Duration",
                value=f"{length_ms // 1000}s",
            ))

        disambiguation = data.get("disambiguation")
        if disambiguation:
            facts.append(EnrichmentFact(field="Disambiguation", value=disambiguation))

        # ── Artists ───────────────────────────────────────────────────────────
        for ac in data.get("artist-credit", []):
            if isinstance(ac, dict) and "artist" in ac:
                artist_info = ac["artist"]
                artist_name = artist_info.get("name")
                if artist_name:
                    facts.append(EnrichmentFact(field="Artist", value=artist_name))
                    # Sort name
                    sort_name = artist_info.get("sort-name")
                    if sort_name and sort_name != artist_name:
                        facts.append(EnrichmentFact(field="Artist Sort Name", value=sort_name))

        # ── ISRCs ─────────────────────────────────────────────────────────────
        for isrc in data.get("isrcs", []):
            facts.append(EnrichmentFact(field="ISRC", value=isrc))

        # ── Release info ──────────────────────────────────────────────────────
        releases = data.get("releases", [])
        if releases:
            release = releases[0]  # First (usually earliest/canonical) release
            release_title = release.get("title")
            if release_title:
                facts.append(EnrichmentFact(field="Album/Release", value=release_title))
            release_date = release.get("date")
            if release_date:
                facts.append(EnrichmentFact(field="Release Date", value=release_date))
            release_country = release.get("country")
            if release_country:
                facts.append(EnrichmentFact(field="Release Country", value=release_country))

        # ── Tags (genres, styles, instruments, ragas) ─────────────────────────
        # CRITICAL: Raga tags are labeled clearly as external reference.
        tags = data.get("tags", [])
        genre_tags = []
        instrument_tags = []
        raga_tags = []
        other_tags = []
        for tag in tags:
            tag_name = tag.get("name", "").lower()
            if any(raga_kw in tag_name for raga_kw in ["raga", "raag", "rag "]):
                raga_tags.append(tag.get("name", ""))
            elif any(inst_kw in tag_name for inst_kw in [
                "sitar", "tabla", "sarod", "flute", "santoor", "sarangi",
                "harmonium", "mridangam", "veena", "sarangi", "bansuri",
                "violin", "guitar", "piano", "trumpet", "drum", "bass"
            ]):
                instrument_tags.append(tag.get("name", ""))
            elif tag.get("count", 0) >= 1:
                genre_tags.append(tag.get("name", ""))

        if genre_tags:
            facts.append(EnrichmentFact(field="Tags/Genre", value=", ".join(genre_tags[:10])))
        if instrument_tags:
            facts.append(EnrichmentFact(field="Instrumentation (external tag)", value=", ".join(instrument_tags)))
        if raga_tags:
            # CRITICAL: These must be labeled as external reference
            facts.append(EnrichmentFact(
                field="Raga (external reference — NOT a SwarSense prediction)",
                value=(
                    f"{', '.join(raga_tags)}. "
                    "NOTE: This information is an external tag from MusicBrainz and "
                    "has NOT been verified or predicted by SwarSense's raga classifier."
                ),
            ))

        # ── Work relationships (composer, lyricist, language) ─────────────────
        for rel in data.get("work-relations", []) + data.get("work-rels", []):
            work = rel.get("work", {})
            if not work:
                continue
            # Work-level attributes
            language = work.get("language")
            if language:
                facts.append(EnrichmentFact(field="Language", value=language))
            work_type = work.get("type")
            if work_type:
                facts.append(EnrichmentFact(field="Work Type", value=work_type))
            # Work artist relations (composer, lyricist)
            for work_rel in work.get("artist-relations", []):
                rel_type = work_rel.get("type", "")
                artist_name = work_rel.get("artist", {}).get("name")
                if artist_name:
                    if rel_type.lower() == "composer":
                        facts.append(EnrichmentFact(field="Composer", value=artist_name))
                    elif rel_type.lower() in ("lyricist", "writer"):
                        facts.append(EnrichmentFact(field="Lyricist/Writer", value=artist_name))
                    else:
                        facts.append(EnrichmentFact(field=f"Work relationship: {rel_type}", value=artist_name))

        # ── External URLs ─────────────────────────────────────────────────────
        external_links = []
        for url_rel in data.get("url-relations", []):
            url_type = url_rel.get("type", "")
            url_obj = url_rel.get("url", {})
            url_resource = url_obj.get("resource", "")
            if url_resource and url_type:
                external_links.append(f"{url_type}: {url_resource}")
        if external_links:
            facts.append(EnrichmentFact(
                field="External Links",
                value=" | ".join(external_links[:5]),
            ))

        if not facts:
            logger.info(f"[MusicBrainz] Recording {mbid} returned no usable metadata.")
            return EnrichmentResult(sources=[])

        source = EnrichmentSource(
            source_name="MusicBrainz",
            url=mb_url,
            disclaimer=(
                "External reference — retrieved from MusicBrainz (musicbrainz.org). "
                "Not generated by SwarSense. Accuracy depends on community-contributed data."
            ),
            facts=facts,
        )
        logger.info(f"[MusicBrainz] Enriched with {len(facts)} fact(s).")
        return EnrichmentResult(sources=[source])
